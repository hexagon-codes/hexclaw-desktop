export const BRANCH_UI_FIDELITY_SURFACES: readonly BranchUiFidelitySurface[] = [
  ...mainSurfaces,
  ...k12Surfaces,
  ...unreachableExclusions,
]

export const BRANCH_UI_UNREACHABLE_EXCLUSION_IDS = unreachableExclusions.map(
  (surface) => surface.id,
)

export const BRANCH_UI_FIDELITY_MANIFEST = {
  schemaVersion: 1,
  branchIdentity: BRANCH_UI_BRANCH_IDENTITY,
  installedThirdLegRequirement: BRANCH_UI_INSTALLED_THIRD_LEG_REQUIREMENT,
  surfaces: BRANCH_UI_FIDELITY_SURFACES,
  unreachableExclusionIds: BRANCH_UI_UNREACHABLE_EXCLUSION_IDS,
  generatedSummary: {
    total: BRANCH_UI_FIDELITY_SURFACES.length,
    browser: BRANCH_UI_FIDELITY_SURFACES.filter((surface) => surface.runner === 'browser').length,
    tauriNative: BRANCH_UI_FIDELITY_SURFACES.filter((surface) => surface.runner === 'tauri-native')
      .length,
    excluded: unreachableExclusions.length,
  },
} as const

/**
 * Structural validation for import-time/test-time use. This validates the
 * inventory contract only; it intentionally does not turn pending UI evidence
 * into a pass.
 */
export function validateBranchUiFidelityManifest(): readonly string[] {
  const errors: string[] = []
  const seen = new Set<string>()

  for (const surface of BRANCH_UI_FIDELITY_SURFACES) {
    if (seen.has(surface.id)) {
      errors.push(`duplicate surface id: ${surface.id}`)
    }
    seen.add(surface.id)

    if (surface.sourceEntry.length === 0) {
      errors.push(`${surface.id}: sourceEntry must not be empty`)
    }
    if (surface.coveredStates.length === 0) {
      errors.push(`${surface.id}: coveredStates must not be empty`)
    }
    if (!surface.statusReason.trim()) {
      errors.push(`${surface.id}: statusReason must not be empty`)
    }

    const excluded = surface.currentStatus === 'excluded'
    if (excluded) {
      if (surface.kind !== 'exclusion') {
        errors.push(`${surface.id}: excluded status requires kind=exclusion`)
      }
      if (surface.priority !== 'EXCLUDE') {
        errors.push(`${surface.id}: excluded status requires priority=EXCLUDE`)
      }
      if (surface.readySelector !== null) {
        errors.push(`${surface.id}: an unreachable exclusion must not claim a ready selector`)
      }
      if (surface.installedThirdLeg !== 'not-applicable') {
        errors.push(`${surface.id}: an unreachable exclusion must not require an installed leg`)
      }
      continue
    }

    if (!surface.readySelector?.trim()) {
      errors.push(`${surface.id}: reachable surface requires readySelector`)
    }
    if (surface.priority === 'EXCLUDE') {
      errors.push(`${surface.id}: reachable surface must not use EXCLUDE priority`)
    }
    if (surface.installedThirdLeg !== 'required') {
      errors.push(`${surface.id}: every reachable surface requires the installed third leg`)
    }
    if (surface.oracle === 'pixel' && surface.prototype === null) {
      errors.push(`${surface.id}: pixel oracle requires a prototype locator`)
    }
    if (
      surface.runner === 'tauri-native' &&
      surface.oracle !== 'native' &&
      surface.oracle !== 'blocked'
    ) {
      errors.push(`${surface.id}: native runner requires native or blocked oracle`)
    }
    if (surface.oracle === 'native' && surface.runner !== 'tauri-native') {
      errors.push(`${surface.id}: native oracle requires tauri-native runner`)
    }
  }

  if (!BRANCH_UI_INSTALLED_THIRD_LEG_REQUIREMENT.mandatory) {
    errors.push('installed third leg must remain mandatory')
  }
  if (BRANCH_UI_UNREACHABLE_EXCLUSION_IDS.length !== unreachableExclusions.length) {
    errors.push('unreachable exclusion export is incomplete')
  }

  return errors
}

export function assertBranchUiFidelityManifest(): void {
  const errors = validateBranchUiFidelityManifest()
  if (errors.length > 0) {
    throw new Error(`Invalid branch UI fidelity manifest:\n${errors.join('\n')}`)
  }
}
